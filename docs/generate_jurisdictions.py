"""
Writes docs/source/jurisdictions.rst from the source registry.

Run after changing a source (its versions, languages, identifiers or options):

    poetry run python docs/generate_jurisdictions.py
"""
from pathlib import Path

from tulit.sources import get_source, list_sources

LANGUAGES = {
    'eng': 'English', 'bul': 'Bulgarian', 'ces': 'Czech', 'dan': 'Danish', 'deu': 'German', 'ell': 'Greek',
    'est': 'Estonian', 'fin': 'Finnish', 'fra': 'French', 'gle': 'Irish', 'hrv': 'Croatian', 'hun': 'Hungarian',
    'ita': 'Italian', 'lav': 'Latvian', 'lit': 'Lithuanian', 'ltz': 'Luxembourgish', 'mlt': 'Maltese',
    'nld': 'Dutch', 'pol': 'Polish', 'por': 'Portuguese', 'ron': 'Romanian', 'slk': 'Slovak', 'slv': 'Slovenian',
    'spa': 'Spanish', 'swe': 'Swedish',
}


def main() -> None:
    lines = [
        'Jurisdictions',
        '=============',
        '',
        '.. This page is generated by docs/generate_jurisdictions.py from the source registry; edit the sources.',
        '',
        'tulit retrieves the legislation of the European Union and of its 27 Member States from their',
        'official sources. For each, the versions it delivers (``original``: the act as adopted or',
        'published; ``consolidated``: the text in force on a date), the languages, and the identifiers',
        '``tulit.fetch`` accepts. ``tulit sources`` prints the same list.',
        '',
    ]
    for code in list_sources():
        source = get_source(code)
        title = f'{source.name} ({code})'
        languages = ', '.join(f'{LANGUAGES.get(lang, lang)} (``{lang}``)' for lang in source.languages)
        lines += [
            title,
            '-' * len(title),
            '',
            f'**Source**: {source.source_name}',
            '',
            f"**Versions**: {', '.join(f'``{v}``' for v in source.versions)}"
            f' (default ``{source.default_version}``)',
            '',
            f'**Languages**: {languages}',
            '',
            f'**Identifiers**: {source.identifier_help}',
            '',
        ]
        if source.options:
            lines += [f"**Options**: {', '.join(f'``{o}``' for o in source.options)}", '']
    target = Path(__file__).parent / 'source' / 'jurisdictions.rst'
    target.write_text('\n'.join(lines), encoding='utf-8')
    print(f'wrote {target}')


if __name__ == '__main__':
    main()
